/**
 * Returns brand official info and formats outbound purchase link with affiliate tracking.
 * 
 * @param {string} brandName Name of brand in the catalog
 * @param {string} productUrl Original product URL from the database
 * @returns {object} Brand metadata and direct purchase link
 */
export function getBrandInfo(brandName, productUrl) {
  const brand = BRANDS[brandName] || {
    name: brandName,
    domain: '',
    storeUrl: '',
    couponCode: '',
    discount: '',
    affiliateParam: '',
    verification: 'Check brand seal and official batch verification code on arrival.',
    directDispatch: true
  };

  let purchaseUrl = productUrl || brand.storeUrl;
  if (purchaseUrl && brand.affiliateParam) {
    try {
      const u = new URL(purchaseUrl);
      const [key, val] = brand.affiliateParam.split('=');
      if (key && val) u.searchParams.set(key, val);
      purchaseUrl = u.toString();
    } catch {
      // Retain fallback URL
    }
  }

  return {
    ...brand,
    purchaseUrl
  };
}
